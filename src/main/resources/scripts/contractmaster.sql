CREATE TABLE instrument_master (
    id BIGINT NOT NULL AUTO_INCREMENT,
    token VARCHAR(30) NOT NULL,
    symbol VARCHAR(100) NOT NULL,
    exchange VARCHAR(20) NOT NULL,
    instrument_name VARCHAR(100),
    instrument_type VARCHAR(30) NOT NULL,
    underlying VARCHAR(100),
    strike_price DECIMAL(12, 2),
    option_type VARCHAR(5),
    expiry_date DATE,
    lot_size INT,
    trading_symbol VARCHAR(100),
    formatted_instrument_name VARCHAR(150),
    exchange_segment VARCHAR(30),
    tick_size DECIMAL(10, 4),
    source_file VARCHAR(255),
    imported_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    UNIQUE KEY uk_exchange_token (exchange, token),
    INDEX idx_underlying_expiry (underlying, expiry_date),
    INDEX idx_instrument_type (instrument_type)
);